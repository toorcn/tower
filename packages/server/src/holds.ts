import type { HookPayload, TowerState } from '../../shared/src/index.js';
import { priority } from './claims.js';
import { collisions } from './collision.js';
import { parsePatch, toRelativePath } from './normalise.js';

export function editPaths(tool: 'codex' | 'claude-code', payload: HookPayload, worktree: string): string[] {
  if (payload.hook_event_name !== 'PreToolUse') return [];
  if (tool === 'codex' && payload.tool_name === 'apply_patch') return [...new Set(parsePatch(payload.tool_input?.command ?? '', worktree, payload.cwd).map(e => e.path))];
  if (!['Edit', 'Write', 'MultiEdit'].includes(payload.tool_name ?? '')) return [];
  const path = toRelativePath(payload.tool_input?.file_path ?? '', worktree, payload.cwd);
  return path ? [path] : [];
}

export function heldFiles(state: TowerState, agentId: string, paths: string[]) {
  const assignments = state.collisions.flatMap(collision => {
    const detected = collision.events.find(e => e.type === 'collision.detected');
    if (detected?.type !== 'collision.detected' || !detected.data.agentIds.includes(agentId) || !collision.events.some(e => e.type === 'split.accepted')) return [];
    const proposal = collision.events.filter(e => e.type === 'split.proposed').at(-1);
    if (proposal?.type !== 'split.proposed') return [];
    return proposal.data.assignments.filter(a => a.agentId !== agentId).flatMap(a => a.files.filter(path => paths.includes(path)).map(path => ({
      path, heldBy: a.agentId, collisionId: collision.collisionId,
      reason: `Tower: ${path} is assigned to ${state.agents.find(agent => agent.id === a.agentId)?.pilot ?? a.agentId}'s agent by the accepted split. ${proposal.data.rationale} Work on your assigned files instead.`,
    })));
  });
  return [...assignments, ...collisions(state).filter(pair => pair.agentIds.includes(agentId)).flatMap(pair => pair.files.filter(path => paths.includes(path)).flatMap(path => {
    const claims = state.claims.filter(c => c.path === path && pair.agentIds.includes(c.agentId));
    const owner = priority(claims[0], claims[1]);
    if (owner.agentId === agentId) return [];
    const agent = state.agents.find(a => a.id === owner.agentId)!;
    const collision = state.collisions.find(c => !c.events.some(e => e.type === 'collision.resolved') && c.events.some(e => e.type === 'collision.detected' && e.data.agentIds.every(id => pair.agentIds.includes(id))));
    if (!collision) return [];
    return [{ path, heldBy: owner.agentId, collisionId: collision.collisionId,
      reason: `Tower: ${path} is held by ${agent.pilot}'s agent (task: ${agent.intent ?? 'working'}). A split is being negotiated. Do not edit this file or work around the hold. Carry on with files outside this list: ${pair.files.join(', ')}.` }];
  }))];
}
